"""Looching's data from the original NeXT sources (run by tools/build.py generate()).

  gen_looch.py OUT.h

Reads assets/looching/LoochWaves.h (Brad Garton's wavetable and pitch data, 1991, as it shipped) and
assets/looching/LoochityDog.tiff (the application icon) and writes, as exact integers:

  LW_WAVE[3][7][64]   the three timbre sets of seven waves: 7 partials each (LoochWaves.h freqs / amps; a row with
                      six amplitudes has a 0 seventh), phases 0, summed and normalised to a peak of 32767, sampled at
                      64 points (MusicKit Partials -> a 64-sample table, Bark.m setTable:length:64)
  LW_ROW_N[5]         toneindex[]: the original picks index ranInt(0, LW_ROW_N) from a row, inclusive
  LW_PITCH_C[5][15]   the pitch rows in centi-Hz; entry 14 is what the original read one past the row's end (the
                      next row's first entry; past the table: 0, silent), docs/SPEC.md "The quirks"
  LW_ROW_SET[5]       the timbre set each tone row selects (Looching.m trOriginal .. trBach)
  LW_SINE[256]        one sine cycle, Q15 (the vibrato oscillators)
  NOTE_C[128]         the MIDI notes' frequencies in centi-Hz (A4 = 44000): MIDI out finds the nearest
  DOG_PX[48 * 48]     the icon: 0 white .. 3 black (2-bit grey, NeXT WhiteIsZero), 255 transparent (its alpha plane)
"""
import math
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "looching"


def c_arrays(text):
    """name -> nested lists of numbers, for the plain initialisers in LoochWaves.h"""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = {}
    for m in re.finditer(r"(\w+)\s*((?:\[\d+\])+)\s*=\s*", text):
        i = m.end()
        stack, cur, tok = [], None, ""
        while True:
            ch = text[i]
            if ch == "{":
                new = []
                if cur is not None:
                    cur.append(new)
                stack.append(new)
                cur = new
            elif ch in ",}":
                if tok.strip():
                    cur.append(float(tok))
                tok = ""
                if ch == "}":
                    done = stack.pop()
                    if not stack:
                        out[m.group(1)] = done
                        break
                    cur = stack[-1]
            else:
                tok += ch
            i += 1
    return out


def waves(freqs, amps):
    tabs = []
    for s in range(3):
        for w in range(7):
            fr, am = freqs[s][w], amps[s][w] + [0.0] * (7 - len(amps[s][w]))
            v = [sum(a * math.sin(2 * math.pi * f * i / 64) for f, a in zip(fr, am)) for i in range(64)]
            pk = max(abs(x) for x in v) or 1.0
            tabs.append([int(round(x / pk * 32767)) for x in v])
    return tabs


def dog():
    d = (SRC / "LoochityDog.tiff").read_bytes()
    assert d[:4] == b"MM\x00\x2a", "a big-endian TIFF"
    off = struct.unpack(">I", d[4:8])[0]
    n = struct.unpack(">H", d[off:off + 2])[0]
    tags = {}
    for i in range(n):
        tag, typ, cnt, val = struct.unpack(">HHII", d[off + 2 + 12 * i:off + 14 + 12 * i])
        tags[tag] = (typ, cnt, val >> 16 if typ == 3 and cnt == 1 else val)
    w, h = tags[256][2], tags[257][2]
    assert (w, h) == (48, 48) and tags[258][2] == 2 and tags[277][2] == 2 and tags[284][2] == 2
    so = struct.unpack(">II", d[tags[273][2]:tags[273][2] + 8])     # two planes: grey, alpha
    px = []
    for y in range(h):
        for x in range(w):
            def get(plane):
                b = d[so[plane] + y * 12 + x // 4]
                return (b >> (6 - 2 * (x % 4))) & 3
            px.append(get(0) if get(1) == 3 else 255)
    return px


def rows(name, vals, per, fmt="%d"):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
    return lines


def main():
    a = c_arrays((SRC / "LoochWaves.h").read_text())
    freqs, amps, pitches, toneindex = a["freqs"], a["amps"], a["pitches"], a["toneindex"]
    flat = [p for r in pitches for p in r]                 # the original's memory layout: rows back to back
    pc = []
    for r in range(5):
        row = [int(round(p * 100)) for p in pitches[r]]
        nxt = flat[(r + 1) * 14] if (r + 1) * 14 < len(flat) else 0.0   # one past the row's end
        pc.append(row + [int(round(nxt * 100))])
    tabs = waves(freqs, amps)
    sine = [int(round(32767 * math.sin(2 * math.pi * i / 256))) for i in range(256)]
    px = dog()
    o = ["/* generated by tools/gen_looch.py from assets/looching/ (LoochWaves.h, LoochityDog.tiff): do not edit */",
         "#define LW_SETS 3", "#define LW_WAVES 7", "#define LW_TAB 64", "#define LW_ROWS 5", "#define DOG_W 48",
         "#define DOG_H 48",
         "static const int16_t LW_WAVE[LW_SETS][LW_WAVES][LW_TAB] = {"]
    for si in range(3):
        o.append("    {")
        for t in tabs[si * 7:(si + 1) * 7]:
            o.append("        {" + ", ".join(map(str, t)) + "},")
        o.append("    },")
    o.append("};")
    o.append("static const uint8_t LW_ROW_N[LW_ROWS] = {" + ", ".join(str(int(t)) for t in toneindex) + "};")
    o.append("static const uint32_t LW_PITCH_C[LW_ROWS][15] = {")
    for r in pc:
        o.append("    {" + ", ".join(map(str, r)) + "},")
    o.append("};")
    o.append("static const uint8_t LW_ROW_SET[LW_ROWS] = {0, 1, 1, 2, 0};")
    o.append("static const int16_t LW_SINE[256] = {")
    o += rows("", sine, 16)
    o.append("};")
    o.append("static const uint32_t NOTE_C[128] = {")
    o += rows("", [int(round(44000 * 2 ** ((n - 69) / 12))) for n in range(128)], 12)
    o.append("};")
    o.append("static const uint8_t DOG_PX[DOG_W * DOG_H] = {")
    o += rows("", px, 24)
    o.append("};")
    Path(sys.argv[1]).write_text("\n".join(o) + "\n")
    print(f"looch: {len(tabs)} waves, {len(pc)} rows, icon {len(px)} px -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
